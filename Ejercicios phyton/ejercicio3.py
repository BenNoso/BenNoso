# Ejercicio 3: Número par o impar
# Instrucciones:
# - Pedir al usuario un número entero.
# - Determinar si es par o impar utilizando el operador módulo (%).
# - Mostrar el mensaje correspondiente.

# Tu código aquí:

# Pedir el número:
número = int(input("Inserte un número entero: "))

# Verificar si es par o impar:
if número % 2 == 0:

# Mostrar el mensaje:
# print("El número es par") o print("El número es impar")
   print ("El número", número, "es par")
else:
   print ("El número", número, "es impar")